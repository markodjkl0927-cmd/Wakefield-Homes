/**
 * Minimal CSV export helpers (RFC 4180 quoting, UTF-8 BOM so Excel shows “—” and “→” correctly).
 * Cells that start with = + - @ are prefixed with an apostrophe so spreadsheets never run them as formulas.
 */

type Cell = string | number | boolean | null | undefined

function escapeCell(value: Cell): string {
  let text = value == null ? '' : String(value)
  if (/^[=+\-@\t\r]/.test(text)) text = `'${text}`
  return `"${text.replace(/"/g, '""')}"`
}

export function toCsv(header: string[], rows: Cell[][]): string {
  return [header, ...rows].map((row) => row.map(escapeCell).join(',')).join('\r\n')
}

/** Triggers a browser download of a CSV string via a temporary Blob URL. */
export function downloadCsv(filename: string, csv: string): void {
  const blob = new Blob(['﻿', csv], { type: 'text/csv;charset=utf-8' })
  const url = URL.createObjectURL(blob)
  const link = document.createElement('a')
  link.href = url
  link.download = filename
  link.rel = 'noopener'
  link.style.display = 'none'
  document.body.appendChild(link)
  link.click()
  link.remove()
  window.setTimeout(() => URL.revokeObjectURL(url), 1000)
}
