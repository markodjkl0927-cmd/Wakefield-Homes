import { photos, wp } from './images'

/**
 * View My Home — the client's per-home photo portfolio, rebuilt from https://wakefieldhomeslc.com/view-my-home/
 * (and each /view-my-home/<address>/ page). Every gallery is in stage order and, within a stage, in date order
 * (the date in the file name when there is one, otherwise the order the client uploaded the photos).
 * Captions are the live alt text (shortened), the labels in the file names, or the room shown.
 *
 * Current builds come first (as on the live index), then completed homes, newest first.
 */

export type PortfolioStage = 'site' | 'construction' | 'finishes' | 'completed'
export type PortfolioStatus = 'under-construction' | 'coming-soon' | 'completed' | 'sold'

export interface PortfolioPhoto {
  url: string
  caption: string
  stage: PortfolioStage
  /** yyyy-mm-dd, when the file name records the day the photo was taken. */
  date?: string
}

export interface PortfolioHome {
  /** Route slug: /view-my-home/:slug */
  slug: string
  address: string
  city: string
  /** Community / project name and id (communities.ts). */
  community?: string
  communityId?: string
  lot?: string
  /** Floor plan slug (models.ts), when the live page names the plan. */
  modelSlug?: string
  /** Plan as shown on the card, e.g. "The Hamilton" or "Four-level townhome". */
  planLabel?: string
  status: PortfolioStatus
  /** Published timing, e.g. "Delivery spring 2027". */
  statusNote?: string
  buildOnYourLot?: boolean
  cover: string
  /** A sentence from the live pages. */
  summary?: string
  /** The public listing for this address (listings.ts), when there is one. */
  homeId?: string
  /** The live page this gallery mirrors. */
  sourceUrl: string
  /** In stage and date order. Empty for homes not started yet ("photos coming soon"). */
  photos: PortfolioPhoto[]
}

export const portfolioStageLabels: Record<PortfolioStage, string> = {
  site: 'Site development',
  construction: 'House construction',
  finishes: 'Interior finishes',
  completed: 'Completed home',
}

export const portfolioStatusLabels: Record<PortfolioStatus, string> = {
  'under-construction': 'Under construction',
  'coming-soon': 'Coming soon',
  completed: 'Completed',
  sold: 'Sold',
}

const VMH = 'https://wakefieldhomeslc.com/view-my-home/'

type Row = [file: string, caption: string, date?: string]

function stage(s: PortfolioStage, rows: Row[]): PortfolioPhoto[] {
  return rows.map(([file, caption, date]) => (date ? { url: wp(file), caption, stage: s, date } : { url: wp(file), caption, stage: s }))
}

