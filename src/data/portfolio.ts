export function getPortfolioHome(slug: string | undefined): PortfolioHome | undefined {
  return slug ? portfolioHomes.find((h) => h.slug === slug) : undefined
}

/** The portfolio entry for a public listing (listings.ts id), if the home has a photo page. */
export function portfolioForHome(homeId: string): PortfolioHome | undefined {
  return portfolioHomes.find((h) => h.homeId === homeId)
}

/** A home's photos grouped by stage, in order, skipping empty stages (for the gallery page). */
export function portfolioSections(home: PortfolioHome): { stage: PortfolioStage; label: string; photos: PortfolioPhoto[] }[] {
  return (Object.keys(portfolioStageLabels) as PortfolioStage[])
    .map((s) => ({ stage: s, label: portfolioStageLabels[s], photos: home.photos.filter((p) => p.stage === s) }))
    .filter((g) => g.photos.length > 0)
}
